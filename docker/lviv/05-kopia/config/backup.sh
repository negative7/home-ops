#!/usr/bin/env bash
# Nightly Kopia backup of lviv's irreplaceable data to B2 (<bucket>/lviv-kopia/).
# Writes lviv_kopia_* metrics to node-exporter's textfile directory for alerting.
set -Eeuo pipefail

PROM=/textfile/lviv-kopia.prom
SOURCES=(immich apps sergiy alex)

# Kopia's native b2 backend speaks B2 API v1, which this (v4-only) key is refused on; use B2's S3 API
export AWS_ACCESS_KEY_ID="${B2_KEY_ID}" AWS_SECRET_ACCESS_KEY="${B2_KEY}"

log() {
    echo "$(date -Iseconds) $*"
}

connect() {
    local storage=(s3 --bucket "${B2_BUCKET}" --prefix lviv-kopia/ --endpoint "${B2_S3_ENDPOINT}" --region "${B2_S3_REGION}")
    if kopia repository status >/dev/null 2>&1; then
        return 0
    fi
    if ! kopia repository connect "${storage[@]}" --override-hostname lviv-kopia --override-username root; then
        log "connect failed, creating the repository"
        kopia repository create "${storage[@]}" --override-hostname lviv-kopia --override-username root
    fi
}

set_policies() {
    kopia policy set --global \
        --compression zstd-fastest \
        --keep-latest 7 --keep-hourly 0 --keep-daily 7 --keep-weekly 4 --keep-monthly 12 --keep-annual 0
    # Thumbnails and transcodes are regenerated by Immich
    kopia policy set /sources/immich --add-ignore /thumbs/ --add-ignore /encoded-video/
    # Garage syncs to B2 on its own; gluetun only caches a server list
    kopia policy set /sources/apps \
        --add-ignore /garage/ --add-ignore /garage.old/ --add-ignore /kopia/ --add-ignore /gluetun/ \
        --add-ignore logs/ --add-ignore .cache/ --add-ignore "/qbittorrent/core.*"
    # The PC's Kopia repo, now replaced by the Garage sergiy-pc bucket
    kopia policy set /sources/sergiy --add-ignore /desktop/
}

write_metric() {
    local source=$1 ok=$2
    local now
    now=$(date +%s)
    {
        echo "# HELP lviv_kopia_last_run_success 1 if the last Kopia snapshot of the source succeeded."
        echo "# TYPE lviv_kopia_last_run_success gauge"
        echo "# HELP lviv_kopia_last_success_timestamp_seconds Time of the last successful Kopia snapshot of the source."
        echo "# TYPE lviv_kopia_last_success_timestamp_seconds gauge"
        grep -vE "^#|source=\"${source}\"" "${PROM}" 2>/dev/null || true
        echo "lviv_kopia_last_run_success{source=\"${source}\"} ${ok}"
        if [[ ${ok} == 1 ]]; then
            echo "lviv_kopia_last_success_timestamp_seconds{source=\"${source}\"} ${now}"
        else
            grep -E "^lviv_kopia_last_success_timestamp_seconds\{source=\"${source}\"\}" "${PROM}" 2>/dev/null || true
        fi
    } >"${PROM}.tmp"
    mv "${PROM}.tmp" "${PROM}"
}

run_backups() {
    local source rc=0
    if ! connect || ! set_policies; then
        log "repository unavailable, skipping snapshots"
        for source in "${SOURCES[@]}"; do
            write_metric "${source}" 0
        done
        return 1
    fi
    for source in "${SOURCES[@]}"; do
        log "snapshot ${source}"
        if kopia snapshot create "/sources/${source}"; then
            write_metric "${source}" 1
        else
            log "snapshot ${source} failed"
            write_metric "${source}" 0
            rc=1
        fi
    done
    return "${rc}"
}

sleep_until_backup_time() {
    local now target
    now=$(date +%s)
    # BusyBox date: no "today"/"tomorrow" keywords, but "YYYY-MM-DD HH:MM" and "@epoch" work
    target=$(date -d "$(date +%Y-%m-%d) ${BACKUP_TIME}" +%s)
    if ((target <= now)); then
        target=$((target + 86400))
    fi
    log "next run at $(date -d "@${target}" -Iseconds)"
    sleep $((target - now))
}

while true; do
    sleep_until_backup_time
    run_backups || log "run failed"
done
